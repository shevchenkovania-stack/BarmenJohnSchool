/// Персонаж, упоминаемый в записях Джона.
class JohnCharacter {
  final String name;
  final String role;
  final String mention;

  const JohnCharacter({
    required this.name,
    required this.role,
    required this.mention,
  });
}

/// Ключевое воспоминание (место + дата).
class JohnMemory {
  final String place;
  final int year;
  final String description;

  const JohnMemory({
    required this.place,
    required this.year,
    required this.description,
  });

  /// Формат даты для отображения: "Москва, 1998"
  String get label => '$place, $year';
}
