///
/// ╨₧╤é╨┤╨╡╨╗╤î╨╜╨░╤Å ╤ä╤â╨╜╨║╤å╨╕╤Å, ╤ç╤é╨╛╨▒╤ï ╨┐╤Ç╨░╨▓╨╕╨╗╨╛ ╨▒╤ï╨╗╨╛ ╨╛╨┤╨╕╨╜╨░╨║╨╛╨▓╤ï╨╝ ╨╜╨░ ╨│╨╗╨░╨▓╨╜╨╛╨╣ ╨╕ ╨▓ ╤é╨╡╤ü╤é╨░╤à.
int? daysSince(DateTime? lastVisit, DateTime now) {
  if (lastVisit == null) return null;
  final last = DateTime(lastVisit.year, lastVisit.month, lastVisit.day);
  final today = DateTime(now.year, now.month, now.day);
  return today.difference(last).inDays;
}

/// Что Джон скажет на главной прямо сейчас.
///
/// Правило приоритета: сначала «новые» события (возвращение, серия), потом
/// общее состояние. Так ученик, вернувшийся через неделю, услышит про паузу,
/// а не про вежливое «снова здесь».
JohnMoment johnHomeMoment({
  required int streak,
  required int? daysSinceLastVisit,
  required bool hasAnyProgress,
  DateTime? now,
}) {
  if (!hasAnyProgress) return JohnMoment.freshStart;
  final days = daysSinceLastVisit;
  if (days == null) return JohnMoment.freshStart;
  if (days == 0) {
    // Уже заходил сегодня — напоминаем про серию, если она есть.
    return streak >= 2 ? JohnMoment.streak : JohnMoment.returningToday;
  }
  if (days >= 2) return JohnMoment.returningAfterBreak;
  return streak >= 2 ? JohnMoment.streak : JohnMoment.returningAfterBreak;
}

