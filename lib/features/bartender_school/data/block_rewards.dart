/// Награды за завершение блоков Level 1.
///
/// Каждый блок даёт:
/// - Новый ранг студента
/// - Персональное послание от Джона
/// - Бонусный XP
///
/// Награда показывается один раз при завершении последнего урока блока.
/// Повторный показ невозможен (tracked via [ProgressService.claimedBlockRewards]).
library;

/// Награда за завершение блока.
class BlockReward {
  /// ID блока (A, B, C).
  final String blockId;

  /// Название ранга, который получает студент.
  final String rankTitle;

  /// Эмодзи ранга.
  final String rankEmoji;

  /// Заголовок награды (например, "Блок пройден!").
  final String title;

  /// Персональное послание от Джона.
  final String johnMessage;

  /// Бонусный XP за завершение блока (для ранга).
  final int bonusXp;

  /// Бонусные монеты за завершение блока (для траты на мудрость).
  final int bonusCoins;

  const BlockReward({
    required this.blockId,
    required this.rankTitle,
    required this.rankEmoji,
    required this.title,
    required this.johnMessage,
    required this.bonusXp,
    required this.bonusCoins,
  });
}

